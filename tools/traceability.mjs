// Regenerates §8 "Traceability" of every spec from the REAL test titles (RV-06):
// AC IDs are read from the spec's §3 table; tests are found by grepping it()/test()/test.step()
// titles under frontend/src and frontend/e2e. Run: node tools/traceability.mjs [--check]
// --check exits 1 if any AC has no test (usable in CI).
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SPECS = join(ROOT, 'docs/specs');
const TEST_DIRS = [join(ROOT, 'frontend/src'), join(ROOT, 'frontend/e2e')];

const walk = (d) =>
  readdirSync(d).flatMap((f) => {
    const p = join(d, f);
    return statSync(p).isDirectory() ? walk(p) : /\.spec\.ts$/.test(f) ? [p] : [];
  });

/** Expands "US-01-AC-03/04" → [US-01-AC-03, US-01-AC-04] and "US-01..03" is ignored (not an AC). */
function acIds(title) {
  const out = new Set();
  for (const m of title.matchAll(/(US-\d{2})-AC-(\d{2})((?:\/\d{2})*)/g)) {
    out.add(`${m[1]}-AC-${m[2]}`);
    for (const extra of (m[3] || '').split('/').filter(Boolean)) out.add(`${m[1]}-AC-${extra}`);
  }
  return [...out];
}

const tests = []; // { ac, ref }
for (const file of TEST_DIRS.flatMap(walk)) {
  const src = readFileSync(file, 'utf8');
  const rel = relative(join(ROOT, 'frontend'), file);
  for (const m of src.matchAll(/\b(?:it|test|test\.step|it\.each\([\s\S]*?\))\(\s*(['"`])((?:(?!\1).)*)\1/g)) {
    for (const ac of acIds(m[2])) tests.push({ ac, ref: `\`${rel}\` › ${m[2].replace(/\|/g, '\\|')}` });
  }
}

let missing = 0;
for (const f of readdirSync(SPECS).filter((f) => f.endsWith('.md'))) {
  const path = join(SPECS, f);
  const spec = readFileSync(path, 'utf8');
  const acs = [...new Set([...spec.matchAll(/^\| (US-\d{2}-AC-\d{2}) \|/gm)].map((m) => m[1]))];
  const rows = acs.map((ac) => {
    const refs = tests.filter((t) => t.ac === ac).map((t) => t.ref);
    if (!refs.length) missing++;
    return `| ${ac} | ${refs.length ? refs.join('<br>') : '**no test**'} | ${refs.length ? '✅ covered' : '❌ missing'} |`;
  });
  const table = ['<!-- TRACE:START (generated by tools/traceability.mjs — do not edit by hand) -->', '| AC | Tests (file › title) | Coverage |', '|---|---|---|', ...rows, '<!-- TRACE:END -->'].join('\n');
  const next = spec.replace(/## 8\. Traceability[\s\S]*$/, `## 8. Traceability\n${table}\n`);
  if (!process.argv.includes('--check')) writeFileSync(path, next);
  console.log(`${f}: ${acs.length} ACs, ${rows.filter((r) => r.includes('❌')).length} without test`);
}
if (process.argv.includes('--check') && missing) process.exit(1);
